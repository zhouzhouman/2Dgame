def blank(w, h):
    return [['#' if (x in (0, w - 1) or y in (0, h - 1)) else ',' for x in range(w)] for y in range(h)]

class M:
    def __init__(s, w, h):
        s.w, s.h, s.g = w, h, blank(w, h)
    def put(s, x, y, c):
        s.g[y - 1][x - 1] = c
    def rect(s, x1, y1, x2, y2, c):
        for y in range(y1, y2 + 1):
            for x in range(x1, x2 + 1):
                s.put(x, y, c)
    def room(s, x1, y1, x2, y2, dx):
        s.rect(x1, y1, x2, y2, '#')
        s.rect(x1 + 1, y1 + 1, x2 - 1, y2 - 1, ',')
        s.put(dx, y2, '+')
    def road(s, x1, y1, x2, y2):
        s.rect(x1, y1, x2, y2, '.')
    def ch(s, x, y):
        return s.g[y - 1][x - 1]

